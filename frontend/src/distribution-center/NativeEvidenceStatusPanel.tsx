import { useState } from 'react';
import { useHydraLanguage } from '../i18n';

type EvidenceItem = { target: string; status: string; reason?: string };
type EvidenceReport = {
    schemaVersion: 1;
    fix: 'Fix182';
    releasePackageSha256: string;
    nativeReleaseReady: boolean;
    requiredTargets: string[];
    targets: EvidenceItem[];
};

function parseReport(source: string): EvidenceReport {
    if (source.length > 256 * 1024) throw new Error('Native evidence report is too large');
    const object: unknown = JSON.parse(source);
    if (!object || typeof object !== 'object') throw new Error('Native report must be an object');
    const value = object as Record<string, unknown>;
    if (value.schemaVersion !== 1 || value.fix !== 'Fix182'
        || typeof value.releasePackageSha256 !== 'string'
        || !/^[a-f0-9]{64}$/.test(value.releasePackageSha256)
        || typeof value.nativeReleaseReady !== 'boolean'
        || !Array.isArray(value.requiredTargets) || !Array.isArray(value.targets)) {
        throw new Error('Unsupported or incomplete native evidence report');
    }
    const targets = value.targets as unknown[];
    if (targets.length > 30 || !targets.every(item => item !== null && typeof item === 'object'
        && typeof (item as EvidenceItem).target === 'string'
        && typeof (item as EvidenceItem).status === 'string')) {
        throw new Error('Invalid native evidence target entries');
    }
    const requirements = value.requiredTargets as unknown[];
    if (!requirements.every(item => typeof item === 'string') || requirements.length !== targets.length) {
        throw new Error('Native evidence coverage does not match requirements');
    }
    if (value.nativeReleaseReady && targets.some(item => (item as EvidenceItem).status !== 'SIGNED_EXECUTION_ATTESTED')) {
        throw new Error('Inconsistent native evidence status');
    }
    return value as unknown as EvidenceReport;
}

/** Read-only viewer. Signatures are validated by the trusted CLI/CI, NEVER by this browser import. */
export function NativeEvidenceStatusPanel() {
    const { t } = useHydraLanguage();
    const [report, setReport] = useState<EvidenceReport | null>(null);
    const [error, setError] = useState('');
    async function importFile(file: File | undefined) {
        setReport(null); setError('');
        if (!file) return;
        if (file.size > 256 * 1024) { setError(t('Native evidence report is too large')); return; }
        try { setReport(parseReport(await file.text())); }
        catch { setError(t('Native evidence report is invalid')); }
    }
    return <section className="distribution-native-evidence" aria-label={t('Native release evidence')}>
        <h3>{t('Native release evidence')}</h3>
        <p>{t('Import the read-only report generated by the pinned Fix182 release gate.')}</p>
        <label htmlFor="hydra-native-evidence-file">{t('Import local evidence report')}</label>
        <input id="hydra-native-evidence-file" type="file" accept=".json,application/json"
            onChange={event => void importFile(event.target.files?.[0])}/>
        {error && <p role="alert">{error}</p>}
        {report && <div>
            <p><strong>{t('Reported native release status')}: </strong>{t(report.nativeReleaseReady ? 'Attested in imported report' : 'Not certified')}</p>
            <p><code>SHA-256 {report.releasePackageSha256}</code></p>
            <ul>{report.targets.map(item => <li key={item.target}>
                <strong>{item.target}</strong>: {item.status} {item.reason ? `(${item.reason})` : ''}
            </li>)}</ul>
        </div>}
        <p>{t('Browser import does not verify signatures, logs or build execution. Only the trusted CLI/CI gate can authorize publication.')}</p>
    </section>;
}
