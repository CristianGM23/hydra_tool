from __future__ import annotations
import json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
version=json.loads((ROOT/'config/hydra-version.json').read_text(encoding='utf-8'))
v=version['version']
# Maven project version only: the second <version> after parent block is project version.
p=ROOT/'pom.xml';s=p.read_text(encoding='utf-8')
parent_end=s.index('</parent>')
head,tail=s[:parent_end+9],s[parent_end+9:]
tail=re.sub(r'<version>[^<]+</version>',f'<version>{v}</version>',tail,count=1)
p.write_text(head+tail,encoding='utf-8')
# package + lock root package versions
for rel in ['frontend/package.json','frontend/package-lock.json']:
    p=ROOT/rel
    data=json.loads(p.read_text(encoding='utf-8'))
    data['version']=v
    if rel.endswith('package-lock.json') and isinstance(data.get('packages'),dict) and '' in data['packages']:
        data['packages']['']['version']=v
    p.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
# API contract release metadata; operation inventory remains untouched here.
p=ROOT/'config/api-contract.json'
data=json.loads(p.read_text(encoding='utf-8'))
data['hydraVersion']=v
p.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
# Generated frontend constant; source of truth remains config/hydra-version.json.
out=ROOT/'frontend/src/generated/hydraVersion.ts'
out.write_text(f"/** Generated by scripts/release/sync_version.py. Do not edit manually. */\nexport const HYDRA_VERSION = '{v}' as const;\n",encoding='utf-8')
# Internal Java release constant used only in technical reports/provenance.
p=ROOT/'src/main/java/com/example/editor/product/HydraReleaseVersion.java'
s=p.read_text(encoding='utf-8')
s=re.sub(r'(public static final String VERSION = ")[^"]+(";)',rf'\g<1>{v}\g<2>',s,count=1)
p.write_text(s,encoding='utf-8')
print(v)
