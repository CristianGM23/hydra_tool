behavior_app=read('src/main/java/com/example/editor/metamodel/behavior/OperationBehaviorModelApplicationService.java')
repo=read('src/main/java/com/example/editor/metamodel/behavior/persistence/JsonOperationBehaviorModelRepository.java')
check('ActionOperation registra INVOKE_OPERATION', 'InvokeOperationOperation.class' in action_node and 'name = "INVOKE_OPERATION"' in action_node)
check('INVOKE_OPERATION contiene target y argumentos', all(t in invoke for t in ('target','metamodelOperationId','arguments')))
check('Valor admite parámetro', 'parameterName' in value and 'static ActionValueSource parameter' in value)
check('Fuentes de valor excluyentes', 'exactly one of literal, expressionId or parameterName' in value)
check('EXECUTE_ACTION admite bindings', 'Map<String, ActionValueSource> arguments' in execute)
check('Checker exige COMMAND', 'INVOKE_OPERATION_REQUIRES_COMMAND' in checker)
check('Checker cuenta argumentos', 'OPERATION_ARGUMENT_COUNT_MISMATCH' in checker)
check('Checker revisa acciones anidadas', 'MISSING_NESTED_ACTION_ARGUMENT' in checker and 'UNKNOWN_NESTED_ACTION_ARGUMENT' in checker)
check('Ejecutor implementa INVOKE_OPERATION', 'invokeCommand' in executor and 'case InvokeOperationOperation' in executor)
check('Ejecutor propaga parámetros', 'operationArguments.put' in executor and 'nestedArguments.put' in executor)
check('Ejecutor implementa ATOMIC', 'ActionTransactionPolicy.ATOMIC' in executor)
check('Ejecutor implementa BEST_EFFORT', 'Action completed with errors' in executor and 'messages.add(operation.operationId()' in executor)
check('Ejecutor devuelve undo', 'undoDocument' in read('src/main/java/com/example/editor/validation/action/ActionExecutionResult.java') and 'undoAvailable' in executor)
check('Ejecutor detecta recursión', 'Recursive action execution detected' in executor)
check('Bindings usan almacén canónico JSON', 'CanonicalDocumentStore' in repo and 'OperationBehaviorModel.class' in repo)
check('Bindings tienen validación cruzada', 'OPERATION_BINDING_UNKNOWN_EXPRESSION' in behavior_app and 'OPERATION_BINDING_UNKNOWN_ACTION' in behavior_app)

# O5
runtime=read('src/main/java/com/example/editor/operation/runtime/OperationRuntimeService.java')
adapter=read('src/main/java/com/example/editor/operation/runtime/CanonicalModelRuntimeAdapter.java')
