check('ExpressionNode registra VARIABLE', 'VariableExpressionNode.class' in node and 'name = "VARIABLE"' in node)
check('ExpressionNode registra OPERATION_CALL', 'OperationCallExpressionNode.class' in node and 'name = "OPERATION_CALL"' in node)
check('VARIABLE tiene nombre estable', 'variableName' in variable and 'StableIdentifierPolicy' in variable)
check('OPERATION_CALL tiene target operación y argumentos', all(t in call for t in ('target','operationId','arguments')))
check('Tipado resuelve operaciones', 'inferOperationCall' in typer and 'UNKNOWN_OPERATION' in typer)
check('Tipado comprueba destino', 'OPERATION_TARGET_TYPE_MISMATCH' in typer and 'OPERATION_TARGET_NOT_OBJECT' in typer)
check('Tipado comprueba cardinalidad', 'OPERATION_ARGUMENT_COUNT_MISMATCH' in typer)
check('Tipado comprueba argumentos', 'OPERATION_ARGUMENT_TYPE_MISMATCH' in typer)
check('COMMAND prohibido en expresiones', 'COMMAND_OPERATION_NOT_ALLOWED_IN_EXPRESSION' in typer)
check('Retorno void prohibido', 'VOID_OPERATION_IN_EXPRESSION' in typer)
check('Dependencia OPERATION', 'ExpressionDependencyKind.OPERATION' in deps)
check('Evaluador delega llamadas', 'evaluateOperationCall' in evaluator and 'operationInvoker.invoke' in evaluator)
check('Runtime de consultas usa EXPRESSION', 'OperationImplementationKind.EXPRESSION' in query)
check('Runtime crea variables de parámetros', 'variables.put(operation.parameters().get(indexValue).name()' in query)
check('Runtime detecta recursión', 'Recursive operation call detected' in query)
check('COMMAND no admite binding EXPRESSION', 'COMMAND_OPERATION_EXPRESSION_BINDING' in behavior_validator and 'ValidationSeverity.ERROR' in behavior_validator)

# O4
