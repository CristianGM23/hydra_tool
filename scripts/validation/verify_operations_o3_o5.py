check('Runtime publica catálogo', 'OperationRuntimeCatalog catalog' in runtime)
check('Catálogo incluye subtipos', 'applicableClasses' in runtime and 'isSameOrSubtype' in runtime)
check('Runtime ejecuta consultas', 'OperationImplementationKind.EXPRESSION' in runtime and 'queryRuntime.create' in runtime)
check('Runtime ejecuta comandos', 'OperationImplementationKind.ACTION' in runtime and 'actionExecutor.execute' in runtime)
check('Runtime usa snapshot', 'modelService.snapshot' in runtime and 'modelService.restore' in runtime)
check('Runtime conserva historial undo acotado', 'BoundedHistoryStore<ModelDocumentService.ModelSnapshot>' in runtime and 'new BoundedHistoryStore<>(sessionProperties.getMaxActive(), 20)' in runtime)
check('Adaptador aplica atributos', 'setAttribute' in adapter and 'clearAttribute' in adapter)
check('Adaptador aplica referencias', 'syncReferences' in adapter and 'removeReference' in adapter)
check('Adaptador crea y borra elementos', 'addElement' in adapter and 'deleteElement' in adapter)
check('ModelDocumentService expone snapshot', 'public ModelSnapshot snapshot' in model_service and 'public ModelDocumentResponse restore' in model_service)
check('API expone catálogo', 'operation-runtime' in controller and '@GetMapping' in controller)
check('API expone invoke', '@PostMapping("/api/models/{modelId}/operations/{operationId}")' in controller)
