check('API frontend ejecuta y deshace', 'invokeModelOperation' in api and 'undoModelOperation' in api)
check('Bindings configuran superficies', "'ui.surfaces'" in binding_ui and all(x in binding_ui for x in ('BUTTON','FORM','PALETTE','MENU')))
check('Diseñador guarda bindings', 'createOperationBehaviorModel' in designer and 'replaceOperationBehaviorModel' in designer and 'OperationBindingDesigner' in designer)
workspace=read('frontend/src/model-editor/ModelEditorWorkspace.tsx')
check('Aplicación integra runtime', 'loadOperationRuntimeCatalog' in app and 'OperationRuntimePanel' in workspace)

# Contratos, recursos y tests
for schema in ('expression-model-1.0.schema.json','action-model-1.0.schema.json','validation-model-1.0.schema.json'):
    data=json.loads(read('src/main/resources/schemas/validation/'+schema)); check('JSON válido '+schema, isinstance(data,dict) and data.get('$schema'))
check('Schema expresión publica OPERATION_CALL', 'operationCallNode' in read('src/main/resources/schemas/validation/expression-model-1.0.schema.json'))
check('Schema acción publica INVOKE_OPERATION', 'invokeOperation' in read('src/main/resources/schemas/validation/action-model-1.0.schema.json'))
check('Schema validación publica OPERATION', '"OPERATION"' in read('src/main/resources/schemas/validation/validation-model-1.0.schema.json'))
check('Test Java O3', (ROOT/'src/test/java/com/example/editor/semantic/expression/OperationCallExpressionTests.java').is_file())
check('Test Java O4', (ROOT/'src/test/java/com/example/editor/validation/action/OperationActionExecutionTests.java').is_file())
check('Test frontend bindings', (ROOT/'frontend/src/validation-designer/OperationBindingDesigner.test.tsx').is_file())
check('Test frontend runtime', (ROOT/'frontend/src/operation-runtime/OperationRuntimePanel.test.tsx').is_file())
check('Documentación arquitectura actual', (ROOT/'docs/architecture/HYDRA_ARCHITECTURE.md').is_file())
check('Documentación de validación actual', (ROOT/'docs/validation/HYDRA_VALIDATION.md').is_file())

failed=[label for label,ok in checks if not ok]
for label,ok in checks: print(f"[{'OK' if ok else 'FAIL'}] {label}")
print(f"RESULTADO O3-O5: {len(checks)-len(failed)}/{len(checks)} comprobaciones correctas")
if failed:
    print('Fallos:',*failed,sep='\n- '); sys.exit(1)
