#!/usr/bin/env python3
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
checks=[]
def text(path): return (ROOT/path).read_text(encoding='utf-8')
def check(name,condition): checks.append((name,bool(condition)))

diagram=text(Path('frontend/src/grammar-designer/GrammarClassDiagram.tsx'))
shared=text(Path('frontend/src/metamodel-designer/MetamodelReadOnlyCanvas.tsx'))
relation=text(Path('frontend/src/metamodel-designer/MetamodelRelationLayer.tsx'))
model=text(Path('frontend/src/grammar-designer/grammarClassDiagramModel.ts'))
exporter=text(Path('frontend/src/grammar-designer/grammarClassDiagramExport.ts'))
monaco=text(Path('frontend/src/grammar-designer/GrammarMonacoEditor.tsx'))
responsive=text(Path('frontend/src/grammar-designer/grammar-designer-responsive.css'))
spanish=text(Path('frontend/src/i18n/currentSpanishCatalogPart15.ts'))

check('grammar diagram converges on canonical Metamodel Designer renderer', 'MetamodelReadOnlyCanvas' in diagram)
check('canonical renderer reuses MetamodelClassNode', 'MetamodelClassNode' in shared)
check('canonical renderer reuses buildMetamodelEdges', 'buildMetamodelEdges' in shared)
check('canonical renderer reuses MetamodelRelationLayer', 'MetamodelRelationLayer' in shared)
check('composition uses canonical filled UML diamond', 'metamodel-containment-diamond' in relation and 'fill="context-stroke"' in relation)
check('aggregation uses canonical open UML diamond', 'metamodel-aggregation-diamond' in relation)
check('generalization uses canonical open triangle', 'metamodel-inheritance-triangle' in relation)
check('ordinary relation keeps canonical directional arrow', 'metamodel-reference-arrow' in relation)
check('shared inferred node size depends on feature content', 'rowUnits' in shared)
check('shared inferred node width grows with longest row', 'longest' in shared)
check('shared inferred node height uses all feature rows', 'rowUnits' in shared and 'height' in shared)
check('diagram does not render a parallel grammar UML node implementation', 'grammar-class-node' not in diagram)
check('shared nodes have robust minimum size', 'Math.max(280' in shared)
check('export menu exposes requested five formats', "['png','svg','jpeg','drawio','plantuml']" in diagram)
check('export supports PlantUML UML semantics', 'buildGrammarPlantUml' in exporter and "'*-->'" in exporter)
check('export supports draw.io UML semantics', 'buildGrammarDrawio' in exporter and 'startArrow=diamond' in exporter)
check('export supports standalone SVG UML semantics', 'buildGrammarDiagramSvg' in exporter and 'diamond-filled' in exporter)
check('export rasterizes SVG to PNG/JPEG without new dependency', 'downloadRaster' in exporter and 'canvas.toBlob' in exporter)
check('Monaco reserves diagnostic gutter', 'lineDecorationsWidth:16' in monaco)
check('Monaco diagnostics decorate line numbers', 'lineNumberClassName:`hydra-monaco-line-number-${kind}`' in monaco)
check('Monaco diagnostics decorate gutter glyphs', 'glyphMarginClassName:`hydra-monaco-glyph-${kind}`' in monaco)
check('Monaco uses decoration collection compatible with current Monaco', 'createDecorationsCollection' in monaco)
check('unused rules have dedicated yellow visual class', "GRAMMAR_UNUSED_RULE'?'unused'" in monaco and '.hydra-monaco-line-number-unused' in responsive)
check('error lines retain red gutter signal', '.hydra-monaco-line-number-error' in responsive and '.hydra-monaco-glyph-error' in responsive)
check('info lines use dedicated non-red signal', '.hydra-monaco-line-number-info' in responsive and '.grammar-problem.info' in responsive)
check('header action labels are constrained to two-line-height control', 'height:44px' in responsive and 'line-height:1.08' in responsive)
check('header action grid reserves sufficient width', 'repeat(4,minmax(150px,1fr))' in responsive)
check('identity configuration remains one desktop row', 'grid-template-columns:minmax(0,.9fr)' in responsive)
check('Spanish catalog contains diagram download label', "'Download diagram': 'Descargar diagrama'" in spanish)
failed=[name for name,ok in checks if not ok]
for name,ok in checks: print(f"[{'OK' if ok else 'FAIL'}] {name}")
print(f"\n{len(checks)-len(failed)}/{len(checks)} checks passed")
if failed: raise SystemExit(1)
