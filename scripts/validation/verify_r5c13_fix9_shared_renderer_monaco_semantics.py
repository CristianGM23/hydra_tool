#!/usr/bin/env python3
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
checks=[]
def text(path): return (ROOT/path).read_text(encoding='utf-8')
def check(name,condition): checks.append((name,bool(condition)))

diagram=text(Path('frontend/src/grammar-designer/GrammarClassDiagram.tsx'))
shared=text(Path('frontend/src/metamodel-designer/MetamodelReadOnlyCanvas.tsx'))
relation=text(Path('frontend/src/metamodel-designer/MetamodelRelationLayer.tsx'))
class_node=text(Path('frontend/src/metamodel-designer/MetamodelClassNode.tsx'))
diagram_core=text(Path('frontend/src/metamodel-designer/diagram.ts'))
monaco=text(Path('frontend/src/grammar-designer/GrammarMonacoEditor.tsx'))
designer=text(Path('frontend/src/grammar-designer/GrammarDesigner.tsx'))
preview=text(Path('frontend/src/grammar-designer/GrammarTextualCustomization.tsx'))
custom=text(Path('frontend/src/grammar-designer/textualCustomization.ts'))
textual=text(Path('frontend/src/textual-model-editor/TextualModelEditor.tsx'))
responsive=text(Path('frontend/src/grammar-designer/grammar-designer-responsive.css'))
legacy=text(Path('frontend/src/grammar-designer/GrammarUmlEdge.tsx'))
exporter=text(Path('frontend/src/grammar-designer/grammarClassDiagramExport.ts'))

check('inferred grammar diagram imports shared MetamodelReadOnlyCanvas', "from '../metamodel-designer/MetamodelReadOnlyCanvas'" in diagram)
check('inferred grammar diagram renders shared MetamodelReadOnlyCanvas', '<MetamodelReadOnlyCanvas' in diagram)
check('shared canvas reuses canonical node builder', 'buildMetamodelNodes' in shared)
check('shared canvas reuses canonical edge builder', 'buildMetamodelEdges' in shared)
check('shared canvas reuses canonical class renderer', 'MetamodelClassNode' in shared)
check('shared canvas reuses canonical enum renderer', 'MetamodelEnumNode' in shared)
check('shared canvas reuses canonical datatype renderer', 'MetamodelDataTypeNode' in shared)
check('shared canvas reuses canonical relation renderer', 'MetamodelRelationLayer' in shared)
check('shared canvas uses canonical ELK layout', 'metamodelElkLayout' in shared)
check('canonical relation renderer defines containment diamond', 'metamodel-containment-diamond' in relation)
check('canonical relation renderer defines aggregation diamond', 'metamodel-aggregation-diamond' in relation)
check('canonical relation renderer defines reference arrow', 'metamodel-reference-arrow' in relation)
check('canonical relation renderer defines inheritance triangle', 'metamodel-inheritance-triangle' in relation)
check('canonical relation renderer maps CONTAINMENT to diamond and arrow', "kind === 'CONTAINMENT'" in relation and "markerStart: 'url(#metamodel-containment-diamond)'" in relation and "markerEnd: 'url(#metamodel-reference-arrow)'" in relation)
check('canonical class nodes keep semantic read-only projection while allowing transient resize', 'readOnly?: boolean' in diagram_core and 'readOnly: true' in shared and 'data.resizeEnabled !== false' in class_node)
check('inferred dimensions ignore automatic React Flow measurements', "change.type !== 'dimensions'" in shared)
check('inferred class sizing accounts for attributes relations operations', 'item.attributes' in shared and 'relations.length' in shared and 'item.operations' in shared)
check('inferred class width grows from longest rendered row', 'const longest' in shared and 'Math.max(280' in shared)
check('inferred class height grows from wrapped row units', 'rowUnits' in shared and 'compartmentHeight' in shared)
check('legacy grammar UML renderer is only a compatibility tombstone', 'GRAMMAR_UML_RENDERER_DEPRECATED' in legacy and 'HydraConnectionTerminatorShape' not in legacy)
check('Monaco uses current decoration collection API', 'createDecorationsCollection' in monaco and 'syntaxDecorationCollection.current.set(next)' in monaco and 'diagnosticDecorationCollection.current.set(next)' in monaco)
check('Monaco keeps deltaDecorations compatibility fallback only', 'else if(editor.deltaDecorations)' in monaco)
check('Monaco applies model markers', "setModelMarkers(model,'hydra-grammar'" in monaco)
check('Monaco decorates line numbers by severity', 'lineNumberClassName:`hydra-monaco-line-number-${kind}`' in monaco)
check('Monaco decorates gutter glyph by severity', 'glyphMarginClassName:`hydra-monaco-glyph-${kind}`' in monaco)
check('Monaco decorates whole diagnostic line', 'className:`hydra-monaco-line-${kind}`' in monaco)
check('Monaco exposes grammar hover', 'registerHoverProvider' in monaco and 'hoverForToken(current,value)' in monaco)
check('Monaco exposes grammar completion', 'registerCompletionItemProvider' in monaco)
check('Monaco exposes go to definition', 'registerDefinitionProvider' in monaco)
check('Monaco exposes find references', 'registerReferenceProvider' in monaco)
check('Monaco exposes native quick fixes', 'registerCodeActionProvider' in monaco and 'monacoQuickFixes' in monaco)
check('Monaco feedback cards expose linked quick fixes', 'onApplyCodeAction(action)' in monaco)
check('Monaco feedback cards expose candidate replacement fixes', 'applyDiagnosticCandidate' in monaco)
check('grammar editor passes symbols to Monaco', 'symbols={currentAnalysis?.symbols??localInspection.symbols}' in designer)
check('grammar editor passes code actions to Monaco', 'codeActions={currentAnalysis?.codeActions??[]}' in designer or 'codeActions={effectiveCodeActions}' in designer)
check('preview uses same effective customization', 'effectiveTextualCustomization(model)' in preview and 'customization={customization}' in preview)
check('preview passes grammar symbols for contextual help', 'symbols={symbols}' in preview)
check('textual model editor uses same effective customization', 'effectiveTextualCustomization(grammarModel)' in textual)
check('runtime customization maps literals to rules', 'literalSymbols' in custom and 'runtimeSymbolForToken' in custom)
check('runtime contextual hover maps actual tokens to configured symbols', 'hoverForToken' in custom and 'runtimeSymbolForToken(c,text)' in custom)
check('syntax decoration CSS is scoped and severity-independent', 'monacoCustomizationCss(scopeClass,customization)' in monaco and '.monaco-editor .${name}' in monaco)
check('Problems error has error-specific card style', '.grammar-problem.error' in responsive)
check('Problems warning has warning-specific card style', '.grammar-problem.warning' in responsive)
check('Problems info has non-error card style', '.grammar-problem.info' in responsive and 'var(--hydra-color-primary-600)' in responsive)
check('Monaco info line number has non-red class', '.hydra-monaco-line-number-info' in responsive)
check('export menu remains available', "['png','svg','jpeg','drawio','plantuml']" in diagram)
check('PlantUML export remains available', 'buildGrammarPlantUml' in exporter)
check('draw.io export remains available', 'buildGrammarDrawio' in exporter)

failed=[name for name,ok in checks if not ok]
for name,ok in checks: print(f"[{'OK' if ok else 'FAIL'}] {name}")
print(f"\n{len(checks)-len(failed)}/{len(checks)} checks passed")
if failed: raise SystemExit(1)
