from pathlib import Path
import re,sys
ROOT=Path(__file__).resolve().parents[2]
checks=[]
def c(name,ok): checks.append((name,bool(ok)))
policy=(ROOT/'src/main/java/com/example/editor/security/process/HydraExternalProcessPolicy.java').read_text()
props=(ROOT/'src/main/java/com/example/editor/security/process/HydraExternalProcessSecurityProperties.java').read_text()
ext=(ROOT/'src/main/java/com/example/editor/integration/verification/ExternalToolProcessRunner.java').read_text()
runner=(ROOT/'src/main/java/com/example/editor/security/process/HydraExternalProcessRunner.java').read_text()
git=(ROOT/'src/main/java/com/example/editor/remote/git/NativeGitRunner.java').read_text()
py=(ROOT/'src/main/java/com/example/editor/metamodel/importing/python/PythonProcessAstAnalyzer.java').read_text()
prod=(ROOT/'src/main/resources/application-production.properties').read_text()
all_java='\n'.join(p.read_text(errors='ignore') for p in (ROOT/'src/main/java').rglob('*.java'))
c('three native launch sites remain explicit',len(re.findall(r'new ProcessBuilder',all_java))==3)
c('shared executable allowlist exists','allowedExecutables' in props and 'validateCommand' in policy)
c('minimal environment clears inherited process environment','environment.clear()' in policy)
c('argument control characters are rejected',"indexOf('\\0')" in policy and "indexOf('\\n')" in policy)
c('technology validation uses shared process policy','new HydraExternalProcessRunner' in ext and 'securityPolicy.validateCommand(request.command())' in runner and 'securityPolicy.configureMinimalEnvironment(builder, request.environment())' in runner)
c('native Git uses shared process policy','securityPolicy.validateCommand(command)' in git and 'configureMinimalEnvironment' in git)
c('Python AST uses isolated mode and shared process policy','"-I"' in py and 'securityPolicy.validateCommand(command)' in py)
c('production requires package signatures','dsl.portability.packages.require-signature=true' in prod)
security_doc=(ROOT/'docs/security/HYDRA_SECURITY.md')
c('security model exists',security_doc.is_file() and all(token in security_doc.read_text(encoding='utf-8') for token in ['untrusted input','ZIP/JAR/WAR/EAR','External processes','credentials']))
process_tests=(ROOT/'src/test/java/com/example/editor/security/process/HydraExternalProcessPolicyTests.java').read_text()
path_tests=(ROOT/'src/test/java/com/example/editor/project/SafeProjectPathResolverTests.java').read_text()
archive_tests=(ROOT/'src/test/java/com/example/editor/metamodel/importing/updatesite/UpdateSiteArchiveReaderTests.java').read_text()
c('security regression tests exist',bool(process_tests))
c('path traversal regression exists','rejectsParentTraversal' in path_tests and '../outside.json' in path_tests)
c('archive traversal regression exists','rejectsArchiveTraversalEntries' in archive_tests and '../outside.ecore' in archive_tests)
c('archive bomb regression exists','rejectsHighlyCompressedArchiveBombs' in archive_tests and 'compression-ratio limit' in archive_tests)
c('symlink escape regression exists','rejectsSymbolicLinksInsideIsolatedWorkspaces' in process_tests)
c('command argument isolation regression exists','rejectsControlCharactersInsteadOfDelegatingToAShell' in process_tests)
c('Git credentials stay out of argv','HYDRA_GIT_PASSWORD' in git and 'command.add(credentials.token())' not in git and 'credential.helper=' in git)
for name,ok in checks: print(('PASS' if ok else 'FAIL')+' - '+name)
print(f'EXTERNAL_PROCESS_SECURITY={sum(ok for _,ok in checks)}/{len(checks)}')
sys.exit(0 if all(ok for _,ok in checks) else 1)
