from __future__ import annotations
from pathlib import Path
import json,re
ROOT=Path(__file__).resolve().parents[2]
SRC=ROOT/'src/main/java'; version=json.loads((ROOT/'config/hydra-version.json').read_text())['version']
verbs={'GetMapping':'get','PostMapping':'post','PutMapping':'put','DeleteMapping':'delete','PatchMapping':'patch'}

def mapping_path(args:str)->str:
    # Prefer path/value attributes, then the first route-looking literal.
    m=re.search(r'(?:path|value)\s*=\s*"([^"]*)"',args,re.S)
    if m:return m.group(1)
    for value in re.findall(r'"([^"]*)"',args):
        if value=='' or value.startswith('/'): return value
    return ''

def join(base:str,sub:str)->str:
    value=(base.rstrip('/')+'/'+sub.lstrip('/')).replace('//','/')
    if not value.startswith('/'):value='/'+value
    return value or '/'

def method_name(tail:str,idx:int)->str:
    # Remove documentation/annotations between the mapping annotation and declaration,
    # then take the identifier immediately before the parameter list. The return type may
    # end directly in '>' (ResponseEntity<Foo>save(...)), so whitespace is not required.
    declaration=re.sub(r'^\s*(?:(?:/\*.*?\*/|//[^\n]*(?:\n|$)|@[A-Za-z0-9_$.]+(?:\([^)]*\))?)\s*)*','',tail,flags=re.S)
    m=re.search(r'\b(?:public|protected|private)\b\s+.*?\b([A-Za-z_$][A-Za-z0-9_$]*)\s*\(',declaration,re.S)
    return m.group(1) if m else f'operation{idx}'


ops=[]
for file in sorted(SRC.rglob('*.java')):
    text=file.read_text(errors='ignore')
    if '@RestController' not in text: continue
    classpos=text.find('class ')
    prefix=text[:classpos] if classpos>=0 else text
    cms=list(re.finditer(r'@RequestMapping\s*(?:\((.*?)\))?',prefix,re.S))
    base=mapping_path(cms[-1].group(1) or '') if cms else ''
    idx=0
    for m in re.finditer(r'@(GetMapping|PostMapping|PutMapping|DeleteMapping|PatchMapping)\s*(?:\((.*?)\))?',text,re.S):
        idx+=1; ann=m.group(1); args=m.group(2) or ''; sub=mapping_path(args); path=join(base,sub)
        name=method_name(text[m.end():m.end()+4000],idx)
        opid=re.sub(r'[^A-Za-z0-9_]','_',f'{file.stem}_{name}_{verbs[ann]}')
        ops.append({'method':verbs[ann],'path':path,'operationId':opid,'controller':file.stem})
# Operation IDs are part of the generated TypeScript surface; duplicates would silently
# overwrite properties. Fail generation instead of producing a client with ambiguous calls.
operation_ids=[op['operationId'] for op in ops]
if len(operation_ids)!=len(set(operation_ids)):
    duplicates=sorted({item for item in operation_ids if operation_ids.count(item)>1})
    raise SystemExit('Duplicate generated operationId(s): '+', '.join(duplicates))
# Stable de-duplication; duplicate exact routes are a release error and remain visible to verifier.
ops.sort(key=lambda x:(x['path'],x['method'],x['operationId']))
contract={'schemaVersion':'1.0','hydraVersion':version,'operationCount':len(ops),'operations':ops}
(ROOT/'config/api-contract.json').write_text(json.dumps(contract,indent=2,ensure_ascii=False)+'\n')
# YAML intentionally schema-light: route/version contract first, DTO schemas remain source-owned until generated model typing is introduced.
lines=['openapi: 3.1.0','info:','  title: HYDRA API',f'  version: {version}','  description: Generated from Spring MVC controller mappings.','servers:','  - url: /','paths:']
by={}
for op in ops:by.setdefault(op['path'],[]).append(op)
for path,items in sorted(by.items()):
    lines.append(f'  {path}:')
    for op in items:
        lines += [f"    {op['method']}:",f"      operationId: {op['operationId']}",f"      tags: [{op['controller']}]",'      responses:',"        '200':",'          description: Successful HYDRA response',"        '400':",'          description: Actionable HYDRA problem response']
(ROOT/'docs/api/hydra-openapi.yaml').write_text('\n'.join(lines)+'\n')
# Generated TS route registry and generic client.
ts=['/** Generated by scripts/api/generate_openapi.py. Do not edit manually. */',"import { backendFetch } from '../backendFetch';",'', 'export const HYDRA_API_OPERATIONS = {']
for op in ops:ts.append(f"  {json.dumps(op['operationId'])}: {{ method: {json.dumps(op['method'].upper())}, path: {json.dumps(op['path'])} }},")
ts += ['} as const;','export type HydraApiOperationId = keyof typeof HYDRA_API_OPERATIONS;','', 'export function hydraApiPath(operationId: HydraApiOperationId, parameters: Record<string,string|number> = {}): string {','  let path: string = HYDRA_API_OPERATIONS[operationId].path;','  for (const [key,value] of Object.entries(parameters)) path = path.replace(`{${key}}`, encodeURIComponent(String(value)));','  return path;','}','','export async function hydraApiRequest(operationId: HydraApiOperationId, parameters: Record<string,string|number> = {}, init: RequestInit = {}): Promise<Response> {','  const operation = HYDRA_API_OPERATIONS[operationId];','  return backendFetch(hydraApiPath(operationId, parameters), { ...init, method: init.method ?? operation.method });','}']
(ROOT/'frontend/src/api/generated/hydraApiClient.ts').write_text('\n'.join(ts)+'\n')
print(f'OPENAPI_GENERATED operations={len(ops)} version={version}')
