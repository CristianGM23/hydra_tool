package com.example.editor.metamodel.export;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;
import org.springframework.stereotype.Component;
import com.example.editor.metamodel.core.MetaAttribute;
import com.example.editor.metamodel.core.MetaClass;
import com.example.editor.metamodel.core.MetaDataType;
import com.example.editor.metamodel.core.MetaOperation;
import com.example.editor.metamodel.core.MetaParameter;
import com.example.editor.metamodel.core.MetaRelation;
import com.example.editor.metamodel.core.MetaTypeReference;
import com.example.editor.metamodel.core.MetaTypeReferenceKind;
import com.example.editor.metamodel.core.Multiplicity;
import com.example.editor.metamodel.design.MetamodelDesignException;
import com.example.editor.metamodel.design.MetamodelDesignException.Reason;

/** Generates a dependency-free TypeScript model API from the neutral metamodel. */
@Component
public class TypeScriptMetamodelExporter implements MetamodelBinaryExporter {
    /** Descripción: Ejecuta la operación «format» correspondiente a la responsabilidad de TypeScriptMetamodelExporter. Entradas: no requiere parámetros de entrada. Salida: devuelve el resultado definido por el contrato del método. */ @Override public MetamodelExportFormat format(){return MetamodelExportFormat.TYPESCRIPT;}

    /** Descripción: Ejecuta la operación «export» correspondiente a la responsabilidad de TypeScriptMetamodelExporter. Entradas: context: dato de entrada necesario para la operación. Salida: devuelve el resultado definido por el contrato del método. */ @Override public byte[] export(NeutralMetamodelExportContext context){
        try(ByteArrayOutputStream output=new ByteArrayOutputStream();ZipOutputStream zip=new ZipOutputStream(output,StandardCharsets.UTF_8)){
            add(zip,"src/model.ts",buildModel(context));
            add(zip,"src/index.ts","export * from './model';\n");
            add(zip,"package.json",packageJson(context));
            add(zip,"tsconfig.json",tsconfig());
            add(zip,"README.md",readme(context));
            zip.finish();return output.toByteArray();
        }catch(IOException exception){throw new MetamodelDesignException(Reason.STORAGE_ERROR,"Could not generate TypeScript export",exception);}
    }

    /** Descripción: Crea o prepara el resultado de «buildModel» dentro de TypeScriptMetamodelExporter. Entradas: context: dato de entrada necesario para la operación. Salida: devuelve el resultado definido por el contrato del método. */ private String buildModel(NeutralMetamodelExportContext context){
        StringBuilder out=new StringBuilder("/* Generated by HYDRA from the neutral metamodel. */\n\n");
        context.neutralMetamodel().enums().forEach(value->{
            String name=MetamodelExportSupport.pascal(value.name(),"GeneratedEnum");
            out.append("export enum ").append(name).append(" {\n");
            value.literals().forEach(literal->out.append("  ").append(MetamodelExportSupport.pascal(literal.name(),"VALUE")).append(" = ").append(literal.value()).append(",\n"));
            out.append("}\n\n");
        });
        for(MetaDataType value:context.neutralMetamodel().dataTypes()){
            out.append("export type ").append(MetamodelExportSupport.pascal(value.name(),"GeneratedType")).append(" = string;\n\n");
        }
        for(MetaClass value:context.neutralMetamodel().classes()) appendClass(out,context,value);
        return out.toString();
    }

    /** Descripción: Ejecuta la operación «appendClass» correspondiente a la responsabilidad de TypeScriptMetamodelExporter. Entradas: out: dato de entrada necesario para la operación; context: dato de entrada necesario para la operación; value: valor de entrada que debe procesarse. Salida: no devuelve valor; completa la operación o comunica el fallo mediante el contrato existente. */ private void appendClass(StringBuilder out,NeutralMetamodelExportContext context,MetaClass value){
        String name=MetamodelExportSupport.pascal(value.name(),"GeneratedClass");
        List<String> bases=MetamodelExportSupport.superTypeRelationsFrom(context,value.id()).stream()
                .map(item->MetamodelExportSupport.pascal(MetamodelExportSupport.relationTargetName(context,item),"GeneratedClass")).distinct().toList();
        out.append("export interface ").append(name);
        if(!bases.isEmpty()) out.append(" extends ").append(String.join(", ",bases));
        out.append(" {\n");
        for(MetaAttribute attribute:value.attributes()){
            out.append("  ").append(MetamodelExportSupport.camel(attribute.name(),"value"));
            if(optional(attribute.multiplicity())) out.append('?');
            out.append(": ").append(cardinality(type(context,attribute.type()),attribute.multiplicity())).append(";\n");
        }
        for(MetaRelation relation:MetamodelExportSupport.structuralRelationsFrom(context,value.id())){
            out.append("  ").append(MetamodelExportSupport.camel(relation.name(),"reference"));
            if(optional(relation.targetMultiplicity())) out.append('?');
            String target=MetamodelExportSupport.pascal(MetamodelExportSupport.relationTargetName(context,relation),"GeneratedClass");
            out.append(": ").append(cardinality(target,relation.targetMultiplicity())).append(";\n");
        }
        for(MetaOperation operation:value.operations()) {
            out.append("  ").append(MetamodelExportSupport.camel(operation.name(),"operation")).append('(');
            for(int index=0;index<operation.parameters().size();index++) {
                MetaParameter parameter=operation.parameters().get(index);
                if(index>0) out.append(", ");
                out.append(MetamodelExportSupport.camel(parameter.name(),"arg")).append(": ").append(cardinality(type(context,parameter.type()),parameter.multiplicity()));
            }
            out.append("): ").append(operation.returnsVoid()?"void":cardinality(type(context,operation.returnType()),operation.returnMultiplicity())).append(";\n");
        }
        out.append("}\n\n");
    }

    /** Descripción: Ejecuta la operación «type» correspondiente a la responsabilidad de TypeScriptMetamodelExporter. Entradas: context: dato de entrada necesario para la operación; reference: dato de entrada necesario para la operación. Salida: devuelve el resultado definido por el contrato del método. */ private String type(NeutralMetamodelExportContext context,MetaTypeReference reference){
        if(reference==null)return "unknown";
        if(reference.kind()!=MetaTypeReferenceKind.PRIMITIVE) {
            if(reference.kind()==MetaTypeReferenceKind.EXTERNAL) return "unknown";
            return MetamodelExportSupport.pascal(MetamodelExportSupport.resolveTypeName(context,reference),"GeneratedType");
        }
        return switch(reference.targetId()){
            case "BOOLEAN"->"boolean";
            case "BYTE","SHORT","INTEGER","LONG","FLOAT","DOUBLE","DECIMAL","BIG_INTEGER"->"number";
            case "BINARY"->"Uint8Array";
            case "DATE"->"Date";
            case "OBJECT"->"unknown";
            default->"string";
        };
    }
    /** Descripción: Ejecuta la operación «cardinality» correspondiente a la responsabilidad de TypeScriptMetamodelExporter. Entradas: type: dato de entrada necesario para la operación; multiplicity: dato de entrada necesario para la operación. Salida: devuelve el resultado definido por el contrato del método. */ private String cardinality(String type,Multiplicity multiplicity){return multiplicity!=null&&(multiplicity.unbounded()||multiplicity.upperBound()>1)?"ReadonlyArray<"+type+">":type;}
    /** Descripción: Ejecuta la operación «optional» correspondiente a la responsabilidad de TypeScriptMetamodelExporter. Entradas: multiplicity: dato de entrada necesario para la operación. Salida: devuelve un indicador que expresa el resultado de la condición. */ private boolean optional(Multiplicity multiplicity){return multiplicity==null||multiplicity.lowerBound()==0;}
    /** Descripción: Ejecuta la operación «packageJson» correspondiente a la responsabilidad de TypeScriptMetamodelExporter. Entradas: context: dato de entrada necesario para la operación. Salida: devuelve el resultado definido por el contrato del método. */ private String packageJson(NeutralMetamodelExportContext context){String name=MetamodelExportSupport.camel(context.neutralMetamodel().name(),"hydra-model").toLowerCase(java.util.Locale.ROOT);return "{\n  \"name\": \""+name+"\",\n  \"version\": \"1.0.0\",\n  \"private\": true,\n  \"type\": \"module\",\n  \"scripts\": {\"build\": \"tsc -p tsconfig.json\"},\n  \"devDependencies\": {\"typescript\": \"^5.0.0\"}\n}\n";}
    /** Descripción: Ejecuta la operación «tsconfig» correspondiente a la responsabilidad de TypeScriptMetamodelExporter. Entradas: no requiere parámetros de entrada. Salida: devuelve el resultado definido por el contrato del método. */ private String tsconfig(){return "{\n  \"compilerOptions\": {\"target\": \"ES2022\", \"module\": \"ES2022\", \"strict\": true, \"declaration\": true, \"outDir\": \"dist\"},\n  \"include\": [\"src/**/*.ts\"]\n}\n";}
    /** Descripción: Obtiene la información correspondiente a «readme» dentro de TypeScriptMetamodelExporter. Entradas: context: dato de entrada necesario para la operación. Salida: devuelve el resultado definido por el contrato del método. */ private String readme(NeutralMetamodelExportContext context){return "# "+context.neutralMetamodel().name()+"\n\nGenerated TypeScript model API from HYDRA's neutral metamodel.\n";}
    /** Descripción: Ejecuta la operación «add» correspondiente a la responsabilidad de TypeScriptMetamodelExporter. Entradas: zip: dato de entrada necesario para la operación; path: ruta o ubicación utilizada por la operación; content: valor de entrada que debe procesarse. Salida: no devuelve valor; completa la operación o comunica el fallo mediante el contrato existente. */ private void add(ZipOutputStream zip,String path,String content)throws IOException{zip.putNextEntry(new ZipEntry(path));zip.write(content.getBytes(StandardCharsets.UTF_8));zip.closeEntry();}
}
