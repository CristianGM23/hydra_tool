package com.example.editor.metamodel.export;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

import org.springframework.stereotype.Component;

import com.example.editor.metamodel.core.MetaAttribute;
import com.example.editor.metamodel.core.MetaClass;
import com.example.editor.metamodel.core.MetaDataType;
import com.example.editor.metamodel.core.MetaOperation;
import com.example.editor.metamodel.core.MetaParameter;
import com.example.editor.metamodel.core.MetaRelation;
import com.example.editor.metamodel.core.MetaTypeReference;
import com.example.editor.metamodel.core.MetaTypeReferenceKind;
import com.example.editor.metamodel.core.Multiplicity;
import com.example.editor.metamodel.design.MetamodelDesignException;
import com.example.editor.metamodel.design.MetamodelDesignException.Reason;

/** Genera un módulo JavaScript ES2022 sin dependencias, documentado con JSDoc. */
@Component
public class JavaScriptMetamodelExporter implements MetamodelBinaryExporter {
    /** Descripción: Ejecuta la operación «format» correspondiente a la responsabilidad de JavaScriptMetamodelExporter. Entradas: no requiere parámetros de entrada. Salida: devuelve el resultado definido por el contrato del método. */ @Override public MetamodelExportFormat format() { return MetamodelExportFormat.JAVASCRIPT; }

    @Override
    /** Descripción: Ejecuta la operación «export» correspondiente a la responsabilidad de JavaScriptMetamodelExporter. Entradas: context: dato de entrada necesario para la operación. Salida: devuelve el resultado definido por el contrato del método. */ public byte[] export(NeutralMetamodelExportContext context) {
        try(ByteArrayOutputStream output = new ByteArrayOutputStream(); ZipOutputStream zip = new ZipOutputStream(output, StandardCharsets.UTF_8)) {
            add(zip, "src/model.js", buildModel(context));
            add(zip, "src/index.js", "export * from './model.js';\n");
            add(zip, "package.json", packageJson(context));
            add(zip, "README.md", readme(context));
            zip.finish();
            return output.toByteArray();
        } catch(IOException exception) {
            throw new MetamodelDesignException(Reason.STORAGE_ERROR, "Could not generate JavaScript export", exception);
        }
    }

    /** Descripción: Crea o prepara el resultado de «buildModel» dentro de JavaScriptMetamodelExporter. Entradas: context: dato de entrada necesario para la operación. Salida: devuelve el resultado definido por el contrato del método. */ private String buildModel(NeutralMetamodelExportContext context) {
        StringBuilder out = new StringBuilder("/* Generated by HYDRA from the neutral metamodel. */\n\n");
        context.neutralMetamodel().enums().forEach(value -> {
            String name = MetamodelExportSupport.pascal(value.name(), "GeneratedEnum");
            out.append("export const ").append(name).append(" = Object.freeze({\n");
            value.literals().forEach(literal -> out.append("  ").append(MetamodelExportSupport.pascal(literal.name(), "VALUE"))
                    .append(": ").append(literal.value()).append(",\n"));
            out.append("});\n\n");
        });
        for(MetaDataType value : context.neutralMetamodel().dataTypes()) {
            out.append("/** @typedef {string} ").append(MetamodelExportSupport.pascal(value.name(), "GeneratedType")).append(" */\n\n");
        }
        for(MetaClass value : context.neutralMetamodel().classes()) appendClass(out, context, value);
        return out.toString();
    }

    /** Descripción: Ejecuta la operación «appendClass» correspondiente a la responsabilidad de JavaScriptMetamodelExporter. Entradas: out: dato de entrada necesario para la operación; context: dato de entrada necesario para la operación; value: valor de entrada que debe procesarse. Salida: no devuelve valor; completa la operación o comunica el fallo mediante el contrato existente. */ private void appendClass(StringBuilder out, NeutralMetamodelExportContext context, MetaClass value) {
        String name = MetamodelExportSupport.pascal(value.name(), "GeneratedClass");
        List<String> bases = MetamodelExportSupport.superTypeRelationsFrom(context, value.id()).stream()
                .map(item -> MetamodelExportSupport.pascal(MetamodelExportSupport.relationTargetName(context, item), "GeneratedClass")).distinct().toList();
        out.append("/**\n * Generated model type for ").append(value.name()).append(".\n");
        if(value.kind().name().contains("ABSTRACT")) out.append(" * @abstract\n");
        out.append(" */\nexport class ").append(name);
        if(!bases.isEmpty()) out.append(" extends ").append(bases.get(0));
        out.append(" {\n  constructor() {\n");
        if(!bases.isEmpty()) out.append("    super();\n");
        for(MetaAttribute attribute : value.attributes()) {
            out.append("    /** @type {").append(jsDocCardinality(type(context, attribute.type()), attribute.multiplicity())).append("} */\n")
                    .append("    this.").append(MetamodelExportSupport.camel(attribute.name(), "value")).append(" = ")
                    .append(defaultValue(attribute.multiplicity())).append(";\n");
        }
        for(MetaRelation relation : MetamodelExportSupport.structuralRelationsFrom(context, value.id())) {
            String target = MetamodelExportSupport.pascal(MetamodelExportSupport.relationTargetName(context, relation), "GeneratedClass");
            out.append("    /** @type {").append(jsDocCardinality(target, relation.targetMultiplicity())).append("} */\n")
                    .append("    this.").append(MetamodelExportSupport.camel(relation.name(), "reference")).append(" = ")
                    .append(defaultValue(relation.targetMultiplicity())).append(";\n");
        }
        out.append("  }\n");
        for(MetaOperation operation : value.operations()) appendOperation(out, context, operation);
        out.append("}\n\n");
    }

    /** Descripción: Ejecuta la operación «appendOperation» correspondiente a la responsabilidad de JavaScriptMetamodelExporter. Entradas: out: dato de entrada necesario para la operación; context: dato de entrada necesario para la operación; operation: dato de entrada necesario para la operación. Salida: no devuelve valor; completa la operación o comunica el fallo mediante el contrato existente. */ private void appendOperation(StringBuilder out, NeutralMetamodelExportContext context, MetaOperation operation) {
        out.append("\n  /**\n");
        for(MetaParameter parameter : operation.parameters()) {
            out.append("   * @param {").append(jsDocCardinality(type(context, parameter.type()), parameter.multiplicity())).append("} ")
                    .append(MetamodelExportSupport.camel(parameter.name(), "arg")).append("\n");
        }
        out.append("   * @returns {").append(operation.returnsVoid() ? "void" : jsDocCardinality(type(context, operation.returnType()), operation.returnMultiplicity())).append("}\n   */\n  ")
                .append(MetamodelExportSupport.camel(operation.name(), "operation")).append('(');
        for(int index = 0; index < operation.parameters().size(); index++) {
            if(index > 0) out.append(", ");
            out.append(MetamodelExportSupport.camel(operation.parameters().get(index).name(), "arg"));
        }
        out.append(") {\n    throw new Error('Operation implementation is not generated by HYDRA.');\n  }\n");
    }

    /** Descripción: Ejecuta la operación «type» correspondiente a la responsabilidad de JavaScriptMetamodelExporter. Entradas: context: dato de entrada necesario para la operación; reference: dato de entrada necesario para la operación. Salida: devuelve el resultado definido por el contrato del método. */ private String type(NeutralMetamodelExportContext context, MetaTypeReference reference) {
        if(reference == null) return "*";
        if(reference.kind() != MetaTypeReferenceKind.PRIMITIVE) {
            if(reference.kind() == MetaTypeReferenceKind.EXTERNAL) return "*";
            return MetamodelExportSupport.pascal(MetamodelExportSupport.resolveTypeName(context, reference), "GeneratedType");
        }
        return switch(reference.targetId()) {
            case "BOOLEAN" -> "boolean";
            case "BYTE", "SHORT", "INTEGER", "LONG", "FLOAT", "DOUBLE", "DECIMAL", "BIG_INTEGER" -> "number";
            case "BINARY" -> "Uint8Array";
            case "DATE" -> "Date";
            case "OBJECT" -> "*";
            default -> "string";
        };
    }

    /** Descripción: Ejecuta la operación «jsDocCardinality» correspondiente a la responsabilidad de JavaScriptMetamodelExporter. Entradas: type: dato de entrada necesario para la operación; multiplicity: dato de entrada necesario para la operación. Salida: devuelve el resultado definido por el contrato del método. */ private String jsDocCardinality(String type, Multiplicity multiplicity) {
        return many(multiplicity) ? "Array<" + type + ">" : optional(multiplicity) ? "(" + type + "|null)" : type;
    }
    /** Descripción: Ejecuta la operación «defaultValue» correspondiente a la responsabilidad de JavaScriptMetamodelExporter. Entradas: multiplicity: dato de entrada necesario para la operación. Salida: devuelve el resultado definido por el contrato del método. */ private String defaultValue(Multiplicity multiplicity) { return many(multiplicity) ? "[]" : "null"; }
    /** Descripción: Ejecuta la operación «many» correspondiente a la responsabilidad de JavaScriptMetamodelExporter. Entradas: multiplicity: dato de entrada necesario para la operación. Salida: devuelve un indicador que expresa el resultado de la condición. */ private boolean many(Multiplicity multiplicity) { return multiplicity != null && (multiplicity.unbounded() || multiplicity.upperBound() > 1); }
    /** Descripción: Ejecuta la operación «optional» correspondiente a la responsabilidad de JavaScriptMetamodelExporter. Entradas: multiplicity: dato de entrada necesario para la operación. Salida: devuelve un indicador que expresa el resultado de la condición. */ private boolean optional(Multiplicity multiplicity) { return multiplicity == null || multiplicity.lowerBound() == 0; }
    /** Descripción: Ejecuta la operación «packageJson» correspondiente a la responsabilidad de JavaScriptMetamodelExporter. Entradas: context: dato de entrada necesario para la operación. Salida: devuelve el resultado definido por el contrato del método. */ private String packageJson(NeutralMetamodelExportContext context) {
        String name = MetamodelExportSupport.camel(context.neutralMetamodel().name(), "hydra-model").toLowerCase(java.util.Locale.ROOT);
        return "{\n  \"name\": \"" + name + "\",\n  \"version\": \"1.0.0\",\n  \"private\": true,\n  \"type\": \"module\"\n}\n";
    }
    /** Descripción: Obtiene la información correspondiente a «readme» dentro de JavaScriptMetamodelExporter. Entradas: context: dato de entrada necesario para la operación. Salida: devuelve el resultado definido por el contrato del método. */ private String readme(NeutralMetamodelExportContext context) { return "# " + context.neutralMetamodel().name() + "\n\nGenerated JavaScript ES2022 model API from HYDRA's neutral metamodel. JSDoc preserves the available type information without adding runtime dependencies.\n"; }
    /** Descripción: Ejecuta la operación «add» correspondiente a la responsabilidad de JavaScriptMetamodelExporter. Entradas: zip: dato de entrada necesario para la operación; path: ruta o ubicación utilizada por la operación; content: valor de entrada que debe procesarse. Salida: no devuelve valor; completa la operación o comunica el fallo mediante el contrato existente. */ private void add(ZipOutputStream zip, String path, String content) throws IOException { zip.putNextEntry(new ZipEntry(path)); zip.write(content.getBytes(StandardCharsets.UTF_8)); zip.closeEntry(); }
}
